/**
 * Deterministic engineering Q&A fallback for SafariCharge Assistant when live LLM
 * keys are absent or unavailable. Grounded strictly in verified Oct 2026 KPLC
 * tariff rules and any live SimulationResults snapshot supplied by the client.
 */
import { KPLC_OCT_2026_SURCHARGES, computeAllInRate, TARIFF_PROFILES } from '@/lib/tariff-config';
import type { SimulationResults } from '@/lib/sizing/types';

export interface DeterministicAuditContext {
  prompt: string;
  results?: SimulationResults | null;
}

export function buildDeterministicAuditReply({ prompt, results }: DeterministicAuditContext): string {
  const lower = prompt.toLowerCase();
  const evPeak = computeAllInRate(TARIFF_PROFILES.ev.energy.highRateBase, TARIFF_PROFILES.ev);
  const evOffPeak = computeAllInRate(TARIFF_PROFILES.ev.energy.lowRateBase, TARIFF_PROFILES.ev);
  const domHigh = computeAllInRate(TARIFF_PROFILES.domestic.energy.highRateBase, TARIFF_PROFILES.domestic);

  const lines: string[] = [];
  lines.push('### SafariCharge Deterministic Engineering Audit');

  if (results) {
    lines.push(
      `- **System Configuration (${results.inputs.location.name}):** ${results.solarCapacityKWp} kWp PV, ${results.inverterCapacityKW} kW AC inverter, ${results.batteryCapacityKWh} kWh BESS (DC/AC ratio ${results.actualDcAcRatio}).`
    );
    lines.push(
      `- **Seasonal Production & Autonomy:** ${results.annualPVGeneratedKWh.toLocaleString()} kWh/yr AC yield (${(results.annualUsefulSolarKWh ?? results.selfConsumedKWh).toLocaleString()} kWh/yr useful; ${results.annualCurtailedKWh ?? 0} kWh curtailed; ${results.annualClippedKWh ?? 0} kWh clipped), achieving **${results.systemAutonomyPercent}% autonomy**.`
    );
    lines.push(
      `- **Bankability & LCOE:** CapEx KES ${results.totalCapExKSh.toLocaleString()} ($${results.totalCapExUSD.toLocaleString()}), Year-1 savings $${results.annualSavingsUSD.toLocaleString()}, Simple Payback **${results.simplePaybackYears} yrs**, IRR **${results.irrPercent}%**, Useful LCOE **$${results.lcoeUSDPerKWh}/kWh** vs grid baseline $${results.lcoeBaselineUSDPerKWh}/kWh.`
    );
    if (results.engineeringChecks.inverterBatteryMatch) {
      lines.push(
        `- **Battery–Inverter Match:** ${results.engineeringChecks.inverterBatteryMatch.message}`
      );
    }
    if (results.pvOversizeWarning || results.batteryVoltageWarning) {
      lines.push(
        `- **Active Engineering Warnings:** ${[results.pvOversizeWarning, results.batteryVoltageWarning].filter(Boolean).join(' | ')}`
      );
    }
  } else {
    lines.push(
      '- **No active sizing snapshot attached:** Run or open a site design in `/sizing` to audit site-specific PV, BESS voltage windows, curtailment, and LCOE.'
    );
  }

  if (/tariff|kplc|vat|levy|fcc|ferfa|infa|rate|cost/.test(lower) || !results) {
    const s = KPLC_OCT_2026_SURCHARGES;
    lines.push(
      `- **KPLC Oct 2026 Tariff Basis:** FCC KES ${s.fuelEnergyCost.toFixed(2)}, FERFA KES ${s.ferfa.toFixed(2)}, INFA KES ${s.infa.toFixed(2)}, ERC KES ${s.ercLevy.toFixed(2)}, WARMA KES ${s.wraLevy.toFixed(2)}, REP 5% of base; VAT (16%) applies strictly to \`(base + FCC + FERFA)\`. Effective E-Mobility all-in: **KES ${evPeak.toFixed(2)}/kWh peak**, **KES ${evOffPeak.toFixed(2)}/kWh off-peak** (Domestic peak ~KES ${domHigh.toFixed(2)}/kWh).`
    );
  }

  lines.push(
    '_Generated by deterministic audit engine (v2.3.0) — zero extrapolated figures._'
  );
  return lines.join('\n');
}
